// Icons: tokens/icons/kit.icons.json (the kit's own) and tokens/icons/<language>.icons.json (a design
// language's set) → src/generated/icons.css. Every icon becomes `--mx-icon-<name>`, an SVG as a data
// URL; the kit's on every scope, a language's under its `[data-identity]`. `.mx-glyph[data-icon]` takes
// the one of its name, and base.css draws it as a mask in the text colour.
//
// An icon is a path (drawn with the file's `stroke` width, or filled when the file has no stroke),
// `{ path, fill, viewBox }`, or `{ svg }` (a whole SVG, as a set ships it).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'tokens', 'icons');

/** One icon as an SVG document. */
export function svgOf(icon, set) {
  if (typeof icon === 'object' && icon.svg) return icon.svg.replace(/^\s+|\s+$/g, '');
  const path = typeof icon === 'string' ? icon : icon.path;
  const viewBox = (typeof icon === 'object' && icon.viewBox) || set.viewBox || '0 0 16 16';
  const fill = (typeof icon === 'object' && icon.fill) || !set.stroke;
  const paint = fill ? `fill='black'` : `fill='none' stroke='black' stroke-width='${set.stroke}' stroke-linecap='round' stroke-linejoin='round'`;
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='${viewBox}'><path d='${path}' ${paint}/></svg>`;
}

const url = (svg) => `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}")`;

function read(file) {
  return JSON.parse(readFileSync(join(dir, file), 'utf8'));
}

/** The stylesheet: the kit's icons, each language's, and the rule that gives a glyph its own. */
export function renderIcons() {
  const kit = read('kit.icons.json');
  const names = Object.keys(kit.icons).sort();
  const vars = (set, only) =>
    Object.entries(set.icons)
      .filter(([name]) => !only || only.has(name))
      .map(([name, icon]) => `    --mx-icon-${name}: ${url(svgOf(icon, set))};`)
      .join('\n');
  const blocks = [`  :root,\n  [data-identity] {\n${vars(kit)}\n  }`];
  const known = new Set(names);
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.icons.json') && f !== 'kit.icons.json').sort()) {
    const language = file.replace('.icons.json', '');
    const set = read(file);
    const unknown = Object.keys(set.icons).filter((name) => !known.has(name));
    if (unknown.length) throw new Error(`${file}: not kit icons: ${unknown.join(', ')}`);
    blocks.push(`  [data-identity='${language}'] {\n${vars(set)}\n  }`);
  }
  const rules = names.map((name) => `  .mx-glyph[data-icon='${name}'] {\n    --_icon: var(--mx-icon-${name});\n  }`).join('\n\n');
  return `/* Generated by scripts/build-icons.mjs from tokens/icons/: do not edit. */\n@layer mx.components {\n${blocks.join('\n\n')}\n\n${rules}\n}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = join(root, 'src', 'generated');
  mkdirSync(out, { recursive: true });
  const css = renderIcons();
  writeFileSync(join(out, 'icons.css'), css);
  console.log(`icons: ${Object.keys(read('kit.icons.json').icons).length} icons → src/generated/icons.css`);
}
