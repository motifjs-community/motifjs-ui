/** What the owner calls its parts in the customizer. */
export interface CustomizerNames {
    /** A group of the user's own, as in “New menu”. */
    group: string;
    /** The page of the groups, as in “Menus”. */
    groups: string;
    /** The top as a place to add to and move to, as in “The bar”. */
    top: string;
}
